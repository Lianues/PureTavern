import { cp, mkdir, readdir, readFile, rm, stat, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const harmonyRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const workspaceRoot = path.resolve(harmonyRoot, '../..');
const HARMONY_BOOTSTRAP_PATH = '__pure_tavern/harmony-bootstrap.js';
const HARMONY_BOOTSTRAP_TAG =
  '<script src="/__pure_tavern/harmony-bootstrap.js" data-pure-tavern-platform="harmony"></script>';

async function listFiles(root, relative = '') {
  const directory = path.join(root, relative);
  const entries = await readdir(directory, { withFileTypes: true });
  const files = [];
  for (const entry of entries.sort((left, right) => left.name.localeCompare(right.name))) {
    const child = relative ? `${relative}/${entry.name}` : entry.name;
    if (entry.isDirectory()) files.push(...(await listFiles(root, child)));
    else if (entry.isFile()) files.push(child.replaceAll('\\', '/'));
  }
  return files;
}

export async function syncWebAssets({
  sourceRoot,
  targetRoot,
  manifestSource,
  bootstrapSource = null,
}) {
  const source = path.resolve(sourceRoot);
  const target = path.resolve(targetRoot);
  const index = path.join(source, 'index.html');
  const serviceWorker = path.join(source, 'pure-tavern-assets-service-worker.js');
  for (const required of [index, serviceWorker]) {
    const info = await stat(required).catch(() => null);
    if (!info?.isFile())
      throw new Error(`Harmony web sync requires a production Web build: ${required}`);
  }

  await rm(target, { recursive: true, force: true });
  await mkdir(path.dirname(target), { recursive: true });
  await cp(source, target, { recursive: true, force: true });

  if (bootstrapSource) {
    const bootstrapTarget = path.join(target, HARMONY_BOOTSTRAP_PATH);
    await mkdir(path.dirname(bootstrapTarget), { recursive: true });
    await cp(path.resolve(bootstrapSource), bootstrapTarget, { force: true });

    const indexText = await readFile(index, 'utf8');
    if (!indexText.includes(HARMONY_BOOTSTRAP_TAG)) {
      if (!indexText.includes('<head>')) {
        throw new Error('Harmony web sync could not locate the document head.');
      }
      await writeFile(
        path.join(target, 'index.html'),
        indexText.replace('<head>', `<head>\n    ${HARMONY_BOOTSTRAP_TAG}`),
        'utf8',
      );
    }
  }

  const paths = await listFiles(target);
  const sizes = await Promise.all(
    paths.map((relativePath) => stat(path.join(target, relativePath))),
  );
  const totalBytes = sizes.reduce((sum, info) => sum + info.size, 0);
  const manifest = {
    format: 'pure-tavern-harmony-web-assets',
    fileCount: paths.length,
    totalBytes,
    paths,
  };
  await writeFile(
    path.join(path.dirname(target), 'web-manifest.json'),
    `${JSON.stringify(manifest, null, 2)}\n`,
    'utf8',
  );

  const lines = paths.map((assetPath) => `  ${JSON.stringify(assetPath)},`);
  const sourceText = [
    '// Generated by apps/harmony/scripts/sync-web-assets.mjs. Do not edit.',
    'export const WEB_ASSET_PATHS: Set<string> = new Set([',
    ...lines,
    ']);',
    '',
  ].join('\n');
  await mkdir(path.dirname(manifestSource), { recursive: true });
  await writeFile(manifestSource, sourceText, 'utf8');

  return { fileCount: paths.length, totalBytes, paths };
}

async function main() {
  const sourceRoot = path.join(workspaceRoot, 'apps/web/dist');
  const targetRoot = path.join(harmonyRoot, 'entry/src/main/resources/rawfile/web');
  const manifestSource = path.join(
    harmonyRoot,
    'entry/src/main/ets/generated/WebAssetManifest.ets',
  );
  const result = await syncWebAssets({
    sourceRoot,
    targetRoot,
    manifestSource,
    bootstrapSource: path.join(harmonyRoot, 'runtime/harmony-bootstrap.js'),
  });
  const indexText = await readFile(path.join(targetRoot, 'index.html'), 'utf8');
  if (!indexText.includes('<title>PureTavern</title>')) {
    throw new Error('Harmony web assets do not contain the branded PureTavern index.');
  }
  console.log(
    `Synced ${result.fileCount} PureTavern Web files (${result.totalBytes} bytes) into Harmony rawfile.`,
  );
}

const invokedPath = process.argv[1] ? path.resolve(process.argv[1]) : '';
if (invokedPath === fileURLToPath(import.meta.url)) await main();
