async function verifyDesktopBridgeRuntime(source) {
  const calls = [];
  const callbacks = new Map();
  let nextCallbackId = 1;
  const sandbox = {
    __TAURI_INTERNALS__: {
      async invoke(command, args) {
        calls.push([command, args]);
        return command === 'plugin:event|listen' ? 7 : undefined;
      },
      transformCallback(callback) {
        const id = nextCallbackId++;
        callbacks.set(id, callback);
        return id;
      },
      unregisterCallback(id) {
        callbacks.delete(id);
      },
    },
    __TAURI_EVENT_PLUGIN_INTERNALS__: {
      unregisterListener() {},
    },
  };
  sandbox.window = sandbox;
  const context = createContext(sandbox);
  runInContext(source, context, { filename: 'desktop-local-backend-bridge.js' });
  const bridge = context.__PURE_TAVERN_LOCAL_BACKEND__;
  assert.equal(bridge.protocol, 'pure-tavern-local-backend');
  assert.equal(bridge.protocolVersion, 1);

  await bridge.startRequest({ requestId: 'request-1', method: 'GET' });
  await bridge.cancelRequest('request-1');
  let received = null;
  const handle = await bridge.listen((event) => {
    received = event;
  });
  const listenCall = calls.find(([command]) => command === 'plugin:event|listen');
  callbacks.get(listenCall[1].handler)({ payload: { requestId: 'request-1', type: 'complete' } });
  await handle.remove();

  assert.equal(calls[0][0], 'pure_tavern_local_start_request');
  assert.equal(calls[0][1].request.requestId, 'request-1');
  assert.equal(calls[1][0], 'pure_tavern_local_cancel_request');
  assert.equal(calls[1][1].requestId, 'request-1');
  assert.equal(listenCall[1].event, 'pureTavernLocalServerResponse');
  assert.equal(received.requestId, 'request-1');
  assert.equal(received.type, 'complete');
}
